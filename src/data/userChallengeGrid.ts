export interface GridSquare {
  num: number;
  val: number;
  paid: boolean;
  quarter: string;
  isSpecialMin: boolean; // R$ 1.00 (081, 181, 237, 245)
  isSpecialMax: boolean; // R$ 500.00 (260)
}

export function buildGridSquares(paidNumbers: Set<number>): GridSquare[] {
  return EXACT_SHEET_VALUES.map((val, idx) => {
    const num = idx + 1;
    let quarter = '1º TRIM (001–090)';
    if (num > 270) quarter = '4º TRIM (271–365)';
    else if (num > 180) quarter = '3º TRIM (181–270)';
    else if (num > 90) quarter = '2º TRIM (091–180)';

    return {
      num,
      val,
      paid: paidNumbers.has(num),
      quarter,
      isSpecialMin: val === 1,
      isSpecialMax: val === 500,
    };
  });
}
